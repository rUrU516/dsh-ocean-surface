// Bundle only our local modules; React and react-dom remain Host-provided.
import { readFile, writeFile } from 'node:fs/promises';
const modules = ['appearance.js', 'tapes/dots.js', 'tapes/ocean.js', 'cassette-registry.js', 'cassette-catalog.js', 'cassette-operations.js', 'appearance-model.js', 'effect-runtime.js', 'effect-surface.js', 'deck-transport.js', 'deck-panel.js', 'client-entry.js'];
const sources = [];
for (const name of modules) {
  const source = await readFile(new URL(name, import.meta.url), 'utf8');
  sources.push(source.replace(/^import .+ from '.+';\n/gm, '').replace(/^export (class|function|const) /gm, '$1 '));
}
const output = `// Generated by node build.js — edit the local source modules, not this artifact.\n(() => {\n'use strict';\n${sources.join('\n')}\n})();\n`;
await writeFile(new URL('./client.js', import.meta.url), output);
console.log('Built client.js (self-contained ModuleLoader artifact)');
